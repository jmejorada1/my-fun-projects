#!/usr/bin/env bash
# Shared helpers for scripts/k8s-*.sh. Sourced, never run directly:
#   source "$SCRIPT_DIR/lib-k8s.sh"
# Sourcing it also cd's to the repo root and loads .env, the same way
# docker-run.sh does. See docs/specs/kubernetes-local/spec.md.

if [ "${BASH_SOURCE[0]}" = "${0}" ]; then
  echo "lib-k8s.sh is a library. Source it from a k8s-*.sh script, don't run it." >&2
  exit 1
fi

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

# Same .env docker-compose.yml reads (see .env.example), with the same
# fallbacks as docker-compose.yml, so both stacks agree on every value.
[ -f .env ] && set -o allexport && source .env && set +o allexport
FRONTEND_PORT="${FRONTEND_PORT:-4200}"
POSTGRES_PORT="${POSTGRES_PORT:-5433}"
PROMETHEUS_PORT="${PROMETHEUS_PORT:-9090}"
GRAFANA_PORT="${GRAFANA_PORT:-3000}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-P@55w0rd}"
GRAFANA_ADMIN_PASSWORD="${GRAFANA_ADMIN_PASSWORD:-admin}"

# Context guard (spec §4.7). Every kubectl call goes through kc(), so these
# scripts never act on whatever the *current* kubectl context happens to be
# (e.g. a future EKS cluster).
K8S_CONTEXT="docker-desktop"
K8S_NAMESPACE="imdb"
PART_OF_LABEL="app.kubernetes.io/part-of=imdb"
OVERLAY_DIR="deploy/kubernetes/overlays/local"
GENERATED_DIR="$OVERLAY_DIR/.generated"

# Newest stable Envoy Gateway release that ships an install.yaml asset.
# Checked 2026-11-16 on https://github.com/envoyproxy/gateway/releases.
ENVOY_GATEWAY_VERSION="v1.10.0"

kc() { kubectl --context "$K8S_CONTEXT" "$@"; }

die() { echo "$*" >&2; exit 1; }

# docker build tag -> build context, for the three images the stack uses.
# Tags are :local (not :latest) so imagePullPolicy IfNotPresent never pulls.
image_context() {
  case "$1" in
    imdb/posts:local)    echo "backend/posts" ;;
    imdb/frontend:local) echo "frontend/imdb-ui-angular" ;;
    imdb/loaders:local)  echo "backend/imdb-data-python" ;;
    *) return 1 ;;
  esac
}

build_images() {
  local image ctx
  for image in "$@"; do
    ctx="$(image_context "$image")" || die "Unknown image: $image"
    echo "Building $image from $ctx..."
    docker build -t "$image" "$ctx" || die "Build of $image failed. See the error above."
  done
}

require_numeric_port() {
  case "$2" in
    ''|*[!0-9]*) die "$1='$2' in .env must be a plain number (1-65535)." ;;
  esac
  { [ "$2" -ge 1 ] && [ "$2" -le 65535 ]; } || die "$1=$2 is out of range (1-65535)."
}

# Kustomize can't read env vars, so .env values that end up in manifests
# are written into gitignored patch files the local overlay references.
write_env_patch() {
  require_numeric_port FRONTEND_PORT "$FRONTEND_PORT"
  mkdir -p "$GENERATED_DIR"
  cat > "$GENERATED_DIR/gateway-port.yaml" <<YAML
# Generated by scripts/lib-k8s.sh from .env. Don't edit, don't commit.
- op: replace
  path: /spec/listeners/0/port
  value: ${FRONTEND_PORT}
YAML
  cat > "$GENERATED_DIR/posts-cors.yaml" <<YAML
# Generated by scripts/lib-k8s.sh from .env. Don't edit, don't commit.
apiVersion: apps/v1
kind: Deployment
metadata:
  name: posts
spec:
  template:
    spec:
      containers:
        - name: posts
          env:
            - name: APP_CORS_ALLOWED_ORIGINS
              value: "http://localhost:${FRONTEND_PORT}"
YAML
}

# Prints the fully rendered local overlay. The load-restrictor flag lets the
# overlay's configMapGenerators read deploy/docker/ (spec §4.4, §8.4).
render_local() {
  write_env_patch
  kubectl kustomize --load-restrictor LoadRestrictionsNone "$OVERLAY_DIR"
}

ensure_namespace() {
  kc create namespace "$K8S_NAMESPACE" --dry-run=client -o yaml | kc apply -f - >/dev/null \
    || die "Couldn't create namespace $K8S_NAMESPACE."
}

# Secrets come from .env and are applied imperatively, so they never land in
# git or in rendered output (spec §4.4).
ensure_secrets() {
  kc -n "$K8S_NAMESPACE" create secret generic postgres-credentials \
    --from-literal=POSTGRES_PASSWORD="$POSTGRES_PASSWORD" \
    --dry-run=client -o yaml | kc apply -f - >/dev/null \
    || die "Couldn't create Secret postgres-credentials."
  kc -n "$K8S_NAMESPACE" create secret generic grafana-admin \
    --from-literal=GF_SECURITY_ADMIN_PASSWORD="$GRAFANA_ADMIN_PASSWORD" \
    --dry-run=client -o yaml | kc apply -f - >/dev/null \
    || die "Couldn't create Secret grafana-admin."
}

envoy_gateway_installed() {
  kc get deployment envoy-gateway -n envoy-gateway-system >/dev/null 2>&1
}

# Cluster-wide, installed once. The release's install.yaml also installs
# the Gateway API CRDs.
ensure_envoy_gateway() {
  if envoy_gateway_installed; then
    echo "Envoy Gateway already installed."
  else
    echo "Installing Envoy Gateway $ENVOY_GATEWAY_VERSION..."
    kc apply --server-side -f \
      "https://github.com/envoyproxy/gateway/releases/download/${ENVOY_GATEWAY_VERSION}/install.yaml" \
      >/dev/null || die "Envoy Gateway install failed. See the error above."
  fi
  kc wait --timeout=5m -n envoy-gateway-system deployment/envoy-gateway --for=condition=Available >/dev/null \
    || die "Envoy Gateway didn't become Available within 5 min. Check: kubectl --context $K8S_CONTEXT get pods -n envoy-gateway-system"
}

# Proves a locally built image is visible to the cluster with no registry
# pull (spec T1, open question Q1). imagePullPolicy Never makes the pod fail
# fast with ErrImageNeverPull instead of trying Docker Hub.
probe_image_sharing() {
  local image="$1" pod="image-probe-$RANDOM" phase="" reason="" _
  kc -n "$K8S_NAMESPACE" run "$pod" --image="$image" --image-pull-policy=Never \
    --restart=Never --labels="$PART_OF_LABEL" --command -- true >/dev/null \
    || die "Couldn't create the image probe pod."
  for _ in $(seq 1 60); do
    phase="$(kc -n "$K8S_NAMESPACE" get pod "$pod" -o jsonpath='{.status.phase}' 2>/dev/null)"
    reason="$(kc -n "$K8S_NAMESPACE" get pod "$pod" -o jsonpath='{.status.containerStatuses[0].state.waiting.reason}' 2>/dev/null)"
    case "$phase/$reason" in
      Succeeded/*|Failed/*|*/ErrImageNeverPull) break ;;
    esac
    sleep 1
  done
  kc -n "$K8S_NAMESPACE" delete pod "$pod" --ignore-not-found --wait=false >/dev/null 2>&1
  if [ "$phase" = "Succeeded" ]; then
    return 0
  fi
  echo "The cluster can't see the locally built image $image (pod phase '$phase', reason '${reason:-none}')." >&2
  echo "Docker Desktop's Kubernetes isn't sharing Docker's image store. See open question Q1 in" >&2
  echo "docs/specs/kubernetes-local/spec.md and deploy/kubernetes/README.md#troubleshooting." >&2
  return 1
}

# Names of Envoy's proxy Service for the imdb Gateway (in envoy-gateway-system).
envoy_service_name() {
  kc get svc -n envoy-gateway-system \
    -l "gateway.envoyproxy.io/owning-gateway-name=imdb,gateway.envoyproxy.io/owning-gateway-namespace=$K8S_NAMESPACE" \
    -o jsonpath='{.items[0].metadata.name}' 2>/dev/null
}

# Shared by the -h/--help of every k8s script: prints the leading comment
# block of the calling script (everything after the shebang, up to the
# first non-comment line), without the "# " prefixes.
print_header_help() {
  sed -n '2,/^[^#]/{/^#/s/^# \{0,1\}//p;}' "$1"
}
